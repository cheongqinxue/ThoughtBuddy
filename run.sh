#!/usr/bin/env bash
# ThoughtBuddy experiment stack runner (generic — any experiment config YAML).
#
# The config file names the experiment, its Python entrypoint module, LLM profile,
# stack ports/timeouts, and experiment-specific settings. On start, config is applied
# to config.yaml and vLLM/ThoughtBuddy are launched in the background.
#
# Usage:
#   ./run.sh config/experiments/chess.yaml start
#   ./run.sh config/experiments/chess.yaml status
#   ./run.sh config/experiments/chess.yaml logs [vllm|thoughtbuddy|all]
#   ./run.sh config/experiments/chess.yaml analyze
#   ./run.sh config/experiments/chess.yaml stop
#
# Prerequisite: run smoke tests before any experiment (see AGENTS.md "Test workflow"):
#   ./scripts/verify_vllm && ./scripts/verify_langfuse   # when Langfuse enabled

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNNER=(uv run python -m experiments.runner.cli)

usage() {
  cat <<EOF
Usage: $(basename "$0") <experiment-config.yaml> <command> [args...]

Experiment configs live under config/experiments/ (copy from config/experiments-template/).

Commands:
  start     Apply config, start vLLM + ThoughtBuddy (+ Langfuse when enabled)
  stop      Stop services started by this script
  restart   stop then start
  status    Show PIDs, health checks, and log paths
  logs      Tail logs (default: all). Pass vllm or thoughtbuddy to filter.
  analyze   Experiment-specific summary (via config entrypoint)
  monitor   Watch for critical failures and stop the stack (usually auto-started)

Example:
  $(basename "$0") config/experiments/chess.yaml start
EOF
}

require_command() {
  if ! command -v "$1" >/dev/null 2>&1; then
    echo "error: required command not found: $1" >&2
    exit 1
  fi
}

load_run_env() {
  local config_path="$1"
  if [[ ! -f "${config_path}" ]]; then
    echo "error: experiment config not found: ${config_path}" >&2
    exit 1
  fi

  EXP_CONFIG="${config_path}"
  RUN_ENV="$("${RUNNER[@]}" --config "${EXP_CONFIG}" write-env | tail -n1)"
  # shellcheck disable=SC1090
  set -a
  source "${RUN_ENV}"
  set +a
}

load_manifest_env() {
  if [[ -f "${MANIFEST:-}" ]]; then
    # shellcheck disable=SC1090
    source "${MANIFEST}"
    return 0
  fi
  return 1
}

write_manifest() {
  cat >"${MANIFEST}" <<EOF
# Generated by run.sh — sourced by stop/status
EXP_CONFIG=${EXP_CONFIG}
EXPERIMENT_NAME=${EXPERIMENT_NAME}
EXPERIMENT_ENTRYPOINT=${EXPERIMENT_ENTRYPOINT}
STARTED_AT=${STARTED_AT}
TB_PORT=${TB_PORT}
VLLM_PORT=${VLLM_PORT}
VLLM_PROFILE=${VLLM_PROFILE}
VLLM_PID=${VLLM_PID:-}
TB_PID=${TB_PID:-}
STARTED_LANGFUSE=${STARTED_LANGFUSE:-0}
MONITOR_PID=${MONITOR_PID:-}
RUN_DIR=${RUN_DIR}
LOG_DIR=${LOG_DIR}
PID_DIR=${PID_DIR}
MANIFEST=${MANIFEST}
VLLM_LOG=${VLLM_LOG}
TB_LOG=${TB_LOG}
FAILURE_REPORT=${FAILURE_REPORT}
SKIP_LANGFUSE=${SKIP_LANGFUSE}
STOP_LANGFUSE=${STOP_LANGFUSE}
LLM_AGENT_MODEL=${LLM_AGENT_MODEL}
EOF
}

is_pid_alive() {
  local pid="${1:-}"
  [[ -n "${pid}" ]] && kill -0 "${pid}" 2>/dev/null
}

wait_http() {
  local url="$1"
  local timeout="$2"
  local label="$3"
  local deadline=$((SECONDS + timeout))
  echo "Waiting for ${label} (${url}) ..."
  while ((SECONDS < deadline)); do
    if curl -sf "${url}" >/dev/null 2>&1; then
      echo "${label} ready."
      return 0
    fi
    sleep 2
  done
  echo "error: timed out after ${timeout}s waiting for ${label}" >&2
  echo "Check ${VLLM_LOG} or ${TB_LOG}" >&2
  return 1
}

prepare_stack() {
  cd "${ROOT}"
  "${RUNNER[@]}" --config "${EXP_CONFIG}" apply
  "${RUNNER[@]}" --config "${EXP_CONFIG}" preflight || exit 1
  "${RUNNER[@]}" --config "${EXP_CONFIG}" clear-failure
  mkdir -p "${LOG_DIR}" "${PID_DIR}"
}

start_monitor() {
  if is_pid_alive "$(cat "${PID_DIR}/monitor.pid" 2>/dev/null || true)"; then
    return 0
  fi
  echo "Starting experiment monitor → ${MONITOR_LOG}"
  : >"${MONITOR_LOG}"
  nohup "${BASH_SOURCE[0]}" "${EXP_CONFIG}" _monitor_loop >>"${MONITOR_LOG}" 2>&1 &
  echo $! >"${PID_DIR}/monitor.pid"
  MONITOR_PID="$(cat "${PID_DIR}/monitor.pid")"
}

monitor_loop() {
  while true; do
    sleep "${MONITOR_INTERVAL}"
    local health_json
    health_json="$(curl -sf "http://127.0.0.1:${TB_PORT}/thoughtbuddy/health" 2>/dev/null || true)"
    if [[ -z "${health_json}" ]]; then
      continue
    fi
    if echo "${health_json}" | python3 -c "import json,sys; d=json.load(sys.stdin); sys.exit(0 if d.get('status')=='halted' else 1)" 2>/dev/null; then
      echo "CRITICAL: ThoughtBuddy halted — stopping experiment stack"
      echo "${health_json}" | python3 -m json.tool 2>/dev/null || echo "${health_json}"
      if [[ -f "${FAILURE_REPORT}" ]]; then
        echo "Failure report: ${FAILURE_REPORT}"
        cat "${FAILURE_REPORT}"
      fi
      cmd_stop
      exit 1
    fi
  done
}

start_vllm() {
  if is_pid_alive "$(cat "${PID_DIR}/vllm.pid" 2>/dev/null || true)"; then
    echo "vLLM already running (pid $(cat "${PID_DIR}/vllm.pid"))."
    return 0
  fi

  echo "Starting vLLM (profile=${VLLM_PROFILE} model=${LLM_AGENT_MODEL}) → ${VLLM_LOG}"
  : >"${VLLM_LOG}"
  nohup env VLLM_PROFILE="${VLLM_PROFILE}" "${ROOT}/scripts/start_vllm_agent.sh" >>"${VLLM_LOG}" 2>&1 &
  local pid=$!
  echo "${pid}" >"${PID_DIR}/vllm.pid"
  VLLM_PID="${pid}"

  wait_http "http://127.0.0.1:${VLLM_PORT}/v1/models" "${VLLM_READY_TIMEOUT}" "vLLM"
}

start_langfuse() {
  STARTED_LANGFUSE=0
  if [[ "${SKIP_LANGFUSE}" == "1" ]]; then
    echo "Langfuse skipped (stack.skip_langfuse in experiment config)."
    return 0
  fi
  if [[ "$("${RUNNER[@]}" --config "${EXP_CONFIG}" langfuse-enabled)" != "true" ]]; then
    echo "Langfuse disabled in config.yaml — skipping."
    return 0
  fi

  echo "Starting Langfuse (docker) → ${LANGFUSE_LOG}"
  : >"${LANGFUSE_LOG}"
  if ! "${ROOT}/scripts/start_langfuse" --detach >>"${LANGFUSE_LOG}" 2>&1; then
    echo "warning: Langfuse start failed — see ${LANGFUSE_LOG}" >&2
    return 0
  fi
  STARTED_LANGFUSE=1
}

start_thoughtbuddy() {
  if is_pid_alive "$(cat "${PID_DIR}/thoughtbuddy.pid" 2>/dev/null || true)"; then
    echo "ThoughtBuddy already running (pid $(cat "${PID_DIR}/thoughtbuddy.pid"))."
    return 0
  fi

  echo "Starting ThoughtBuddy (langgraph dev) → ${TB_LOG}"
  : >"${TB_LOG}"
  (
    cd "${ROOT}"
    nohup uv run langgraph dev \
      --no-browser \
      --no-reload \
      --allow-blocking \
      --port "${TB_PORT}" \
      >>"${TB_LOG}" 2>&1 &
    echo $! >"${PID_DIR}/thoughtbuddy.pid"
  )
  TB_PID="$(cat "${PID_DIR}/thoughtbuddy.pid")"

  wait_http "http://127.0.0.1:${TB_PORT}/thoughtbuddy/health" "${TB_READY_TIMEOUT}" "ThoughtBuddy"
}

cmd_start() {
  require_command curl
  require_command uv
  prepare_stack

  if is_pid_alive "$(cat "${PID_DIR}/vllm.pid" 2>/dev/null || true)" \
    && is_pid_alive "$(cat "${PID_DIR}/thoughtbuddy.pid" 2>/dev/null || true)"; then
    echo "Experiment stack already running. Use 'status' or 'stop' first."
    cmd_status
    exit 0
  fi

  STARTED_AT="$(date -Iseconds)"
  VLLM_PID=""
  TB_PID=""
  STARTED_LANGFUSE=0
  MONITOR_PID=""

  start_langfuse
  start_vllm
  start_thoughtbuddy
  start_monitor
  VLLM_PID="$(cat "${PID_DIR}/vllm.pid" 2>/dev/null || true)"
  TB_PID="$(cat "${PID_DIR}/thoughtbuddy.pid" 2>/dev/null || true)"
  MONITOR_PID="$(cat "${PID_DIR}/monitor.pid" 2>/dev/null || true)"
  write_manifest

  local hints
  hints="$("${RUNNER[@]}" --config "${EXP_CONFIG}" start-hints --tb-port "${TB_PORT}" 2>/dev/null || true)"

  cat <<EOF

Experiment stack running in the background.

  Config:      ${EXP_CONFIG}
  Experiment:  ${EXPERIMENT_NAME} (${EXPERIMENT_ENTRYPOINT})
  LLM:         ${VLLM_PROFILE} (${LLM_AGENT_MODEL})
  Health:      http://127.0.0.1:${TB_PORT}/thoughtbuddy/health
  Queue:       http://127.0.0.1:${TB_PORT}/thoughtbuddy/queue
  vLLM:        http://127.0.0.1:${VLLM_PORT}/v1/models
${hints}

Logs:
  vLLM:          ${VLLM_LOG}
  ThoughtBuddy:  ${TB_LOG}
$( [[ "${STARTED_LANGFUSE}" == "1" ]] && echo "  Langfuse:      ${LANGFUSE_LOG} (UI http://localhost:3001)" )

When finished: $(basename "$0") ${EXP_CONFIG} analyze
Stop:          $(basename "$0") ${EXP_CONFIG} stop

EOF
}

stop_pidfile() {
  local name="$1"
  local pidfile="${PID_DIR}/${name}.pid"
  if [[ ! -f "${pidfile}" ]]; then
    return 0
  fi
  local pid
  pid="$(cat "${pidfile}")"
  if is_pid_alive "${pid}"; then
    echo "Stopping ${name} (pid ${pid}) ..."
    kill -TERM "${pid}" 2>/dev/null || true
    for _ in $(seq 1 15); do
      is_pid_alive "${pid}" || break
      sleep 1
    done
    if is_pid_alive "${pid}"; then
      kill -KILL "${pid}" 2>/dev/null || true
    fi
  fi
  rm -f "${pidfile}"
}

cmd_stop() {
  stop_pidfile thoughtbuddy
  stop_pidfile vllm
  stop_pidfile monitor

  if [[ "${STARTED_LANGFUSE:-0}" == "1" && "${STOP_LANGFUSE:-1}" == "1" ]]; then
    echo "Stopping Langfuse ..."
    "${ROOT}/scripts/start_langfuse" stop >>"${LANGFUSE_LOG:-/dev/null}" 2>&1 || true
  fi

  rm -f "${MANIFEST:-}"
  echo "Experiment stack stopped."
}

cmd_status() {
  local vllm_pid tb_pid
  vllm_pid="$(cat "${PID_DIR}/vllm.pid" 2>/dev/null || true)"
  tb_pid="$(cat "${PID_DIR}/thoughtbuddy.pid" 2>/dev/null || true)"

  echo "Experiment config: ${EXP_CONFIG}"
  echo "Experiment:        ${EXPERIMENT_NAME:-unknown} (${EXPERIMENT_ENTRYPOINT:-})"
  echo "Run dir: ${RUN_DIR}"
  [[ -n "${STARTED_AT:-}" ]] && echo "Started: ${STARTED_AT}"
  echo "LLM profile: ${VLLM_PROFILE:-unknown} (${LLM_AGENT_MODEL:-})"

  if is_pid_alive "${vllm_pid}"; then
    echo "vLLM:          running (pid ${vllm_pid})"
  else
    echo "vLLM:          stopped"
  fi
  curl -sf "http://127.0.0.1:${VLLM_PORT}/v1/models" >/dev/null 2>&1 \
    && echo "  └─ HTTP :${VLLM_PORT} OK" \
    || echo "  └─ HTTP :${VLLM_PORT} down"

  if is_pid_alive "${tb_pid}"; then
    echo "ThoughtBuddy:  running (pid ${tb_pid})"
  else
    echo "ThoughtBuddy:  stopped"
  fi
  local health_json
  health_json="$(curl -sf "http://127.0.0.1:${TB_PORT}/thoughtbuddy/health" 2>/dev/null || true)"
  if [[ -n "${health_json}" ]]; then
    if echo "${health_json}" | python3 -c "import json,sys; d=json.load(sys.stdin); sys.exit(0 if d.get('status')=='halted' else 1)" 2>/dev/null; then
      echo "  └─ HTTP :${TB_PORT} HALTED (critical failure — experiment stopped)"
      echo "${health_json}" | python3 -m json.tool 2>/dev/null || echo "${health_json}"
    else
      echo "  └─ HTTP :${TB_PORT} OK"
      echo "${health_json}" | python3 -m json.tool 2>/dev/null || true
    fi
  else
    echo "  └─ HTTP :${TB_PORT} down"
  fi

  if docker ps --format '{{.Names}}' 2>/dev/null | grep -q langfuse; then
    echo "Langfuse:      docker containers running (http://localhost:3001)"
  else
    echo "Langfuse:      not running"
  fi

  echo ""
  echo "Logs:"
  echo "  ${VLLM_LOG}"
  echo "  ${TB_LOG}"
  [[ -f "${LANGFUSE_LOG:-}" ]] && echo "  ${LANGFUSE_LOG}"
  [[ -f "${MONITOR_LOG:-}" ]] && echo "  ${MONITOR_LOG}"
  if [[ -f "${FAILURE_REPORT:-}" ]]; then
    echo ""
    echo "Failure report: ${FAILURE_REPORT}"
    cat "${FAILURE_REPORT}"
  fi
}

cmd_logs() {
  local target="${1:-all}"
  mkdir -p "${LOG_DIR}"
  case "${target}" in
    vllm)
      tail -F "${VLLM_LOG}"
      ;;
    thoughtbuddy | tb)
      tail -F "${TB_LOG}"
      ;;
    all | "")
      tail -F "${VLLM_LOG}" "${TB_LOG}"
      ;;
    *)
      echo "error: unknown log target '${target}' (use vllm, thoughtbuddy, or all)" >&2
      exit 1
      ;;
  esac
}

cmd_analyze() {
  cd "${ROOT}"
  "${RUNNER[@]}" --config "${EXP_CONFIG}" analyze
}

main() {
  cd "${ROOT}"

  if [[ $# -lt 1 ]]; then
    usage
    exit 1
  fi

  local config_arg="$1"
  shift

  if [[ "${config_arg}" == "-h" || "${config_arg}" == "--help" || "${config_arg}" == "help" ]]; then
    usage
    exit 0
  fi

  local cmd="${1:-}"
  if [[ -z "${cmd}" ]]; then
    usage
    exit 1
  fi
  shift || true

  case "${cmd}" in
    _monitor_loop)
      load_manifest_env || load_run_env "${config_arg}"
      monitor_loop
      ;;
    stop | status | logs | analyze)
      if ! load_manifest_env; then
        load_run_env "${config_arg}"
      fi
      STARTED_AT="${STARTED_AT:-}"
      ;;
    *)
      load_run_env "${config_arg}"
      ;;
  esac

  case "${cmd}" in
    start)
      cmd_start
      ;;
    stop)
      cmd_stop
      ;;
    restart)
      cmd_stop || true
      cmd_start
      ;;
    status)
      cmd_status
      ;;
    logs)
      cmd_logs "$@"
      ;;
    analyze)
      cmd_analyze
      ;;
    monitor)
      monitor_loop
      ;;
    -h | --help | help)
      usage
      ;;
    *)
      echo "error: unknown command '${cmd}'" >&2
      usage >&2
      exit 1
      ;;
  esac
}

main "$@"
